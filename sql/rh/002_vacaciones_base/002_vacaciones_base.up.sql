-- Archivo: sql/rh/002_vacaciones_base/002_vacaciones_base.up.sql
-- Objetivo:
--   Crear las 3 tablas base para el control histórico de vacaciones por
--   persona, ejercicio de origen y movimientos contables de saldo en
--   PostgreSQL 17.4, reutilizando public.persona y public.app_users.
-- =============================================================================

BEGIN;

-- 1. Derecho vacacional por persona y ejercicio de origen
CREATE TABLE IF NOT EXISTS public.rh_vacacion_derecho (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id      integer NOT NULL REFERENCES public.persona(id),
  ejercicio_anio  smallint NOT NULL,
  periodo_numero  smallint NOT NULL DEFAULT 1,
  estado          varchar(20) NOT NULL DEFAULT 'ACTIVO',
  observaciones   text NULL,
  creado_por      uuid NULL REFERENCES public.app_users(id),
  actualizado_por uuid NULL REFERENCES public.app_users(id),
  creado_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_rh_vac_derecho_persona_ejercicio_periodo
    UNIQUE (persona_id, ejercicio_anio, periodo_numero),
  CONSTRAINT chk_rh_vac_derecho_anio
    CHECK (ejercicio_anio BETWEEN 2000 AND 2100),
  CONSTRAINT chk_rh_vac_derecho_periodo
    CHECK (periodo_numero >= 1),
  CONSTRAINT chk_rh_vac_derecho_estado
    CHECK (estado IN ('ACTIVO', 'CERRADO', 'CANCELADO'))
);

COMMENT ON TABLE public.rh_vacacion_derecho IS
  'Derecho vacacional de una persona respecto a un ejercicio de origen (y periodo opcional).';

CREATE INDEX IF NOT EXISTS idx_rh_vac_derecho_persona
  ON public.rh_vacacion_derecho (persona_id, ejercicio_anio DESC);

-- 2. Solicitudes y registros de disfrute vacacional
CREATE TABLE IF NOT EXISTS public.rh_vacacion_disfrute (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  derecho_id        integer NOT NULL REFERENCES public.rh_vacacion_derecho(id),
  fecha_inicio      date NOT NULL,
  fecha_fin         date NOT NULL,
  dias_solicitados  numeric(6,2) NOT NULL,
  estado            varchar(20) NOT NULL DEFAULT 'PENDIENTE',
  observaciones     text NULL,
  registrado_por    uuid NULL REFERENCES public.app_users(id),
  autorizado_por    uuid NULL REFERENCES public.app_users(id),
  autorizado_en     timestamptz NULL,
  creado_en         timestamptz NOT NULL DEFAULT now(),
  actualizado_en    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_rh_vac_disfrute_fechas
    CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT chk_rh_vac_disfrute_dias_pos
    CHECK (dias_solicitados > 0),
  CONSTRAINT chk_rh_vac_disfrute_estado
    CHECK (estado IN ('PENDIENTE', 'AUTORIZADO', 'RECHAZADO', 'CANCELADO')),
  CONSTRAINT uq_rh_vac_disfrute_id_derecho
    UNIQUE (id, derecho_id)
);

COMMENT ON TABLE public.rh_vacacion_disfrute IS
  'Solicitudes y disfrutes reales de vacaciones vinculados a un derecho de origen.';

CREATE INDEX IF NOT EXISTS idx_rh_vac_disfrute_derecho
  ON public.rh_vacacion_disfrute (derecho_id, fecha_inicio DESC);

CREATE INDEX IF NOT EXISTS idx_rh_vac_disfrute_estado
  ON public.rh_vacacion_disfrute (estado);

-- 3. Movimientos contables de saldo vacacional (ledger inmutable por diseño)
CREATE TABLE IF NOT EXISTS public.rh_vacacion_movimiento (
  id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  derecho_id               integer NOT NULL REFERENCES public.rh_vacacion_derecho(id),
  tipo_movimiento          varchar(25) NOT NULL,
  dias                     numeric(6,2) NOT NULL,
  fecha_efectiva           date NOT NULL,
  fecha_registro           timestamptz NOT NULL DEFAULT now(),
  disfrute_id              integer NULL,
  movimiento_reversado_id  integer NULL REFERENCES public.rh_vacacion_movimiento(id),
  motivo                   text NULL,
  responsable_id           uuid NULL REFERENCES public.app_users(id),
  CONSTRAINT chk_rh_vac_mov_tipo
    CHECK (tipo_movimiento IN ('ASIGNACION', 'DISFRUTE', 'AJUSTE_POSITIVO', 'AJUSTE_NEGATIVO', 'REVERSO')),
  CONSTRAINT chk_rh_vac_mov_dias_no_cero
    CHECK (dias <> 0),
  CONSTRAINT chk_rh_vac_mov_reverso_self
    CHECK (movimiento_reversado_id IS NULL OR movimiento_reversado_id <> id),
  CONSTRAINT fk_rh_vac_mov_disfrute_coherente
    FOREIGN KEY (disfrute_id, derecho_id)
    REFERENCES public.rh_vacacion_disfrute (id, derecho_id)
);

COMMENT ON TABLE public.rh_vacacion_movimiento IS
  'Libro mayor de movimientos de saldo vacacional. El saldo del derecho es SUM(dias).';

CREATE INDEX IF NOT EXISTS idx_rh_vac_mov_derecho
  ON public.rh_vacacion_movimiento (derecho_id, fecha_efectiva DESC, id DESC);

CREATE UNIQUE INDEX IF NOT EXISTS uq_rh_vac_mov_disfrute_unico
  ON public.rh_vacacion_movimiento (disfrute_id)
  WHERE disfrute_id IS NOT NULL AND tipo_movimiento = 'DISFRUTE';

CREATE UNIQUE INDEX IF NOT EXISTS uq_rh_vac_mov_reverso_unico
  ON public.rh_vacacion_movimiento (movimiento_reversado_id)
  WHERE movimiento_reversado_id IS NOT NULL;

COMMIT;
