BEGIN;

CREATE TABLE IF NOT EXISTS public.rh_asistencia_entrega_mensual (
  id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id               INTEGER NOT NULL REFERENCES public.persona(id),
  anio                     SMALLINT NOT NULL,
  mes                      SMALLINT NOT NULL,
  unidad_medica_id         INTEGER NULL REFERENCES public.unidad_medica(id),
  adscripcion_laboral_id   INTEGER NULL REFERENCES public.rh_adscripcion_laboral(id),

  -- Estado oficial del control mensual de entrega/recepción
  estado                   VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',

  -- Recepción física confirmada por RH (solo poblada cuando estado = 'RECIBIDA')
  fecha_recepcion          TIMESTAMPTZ NULL,
  recibido_por             UUID NULL REFERENCES public.app_users(id),

  -- Observaciones y excepciones administrativas capturadas explícitamente por RH
  observaciones            TEXT NULL,
  excepcion_administrativa BOOLEAN NOT NULL DEFAULT FALSE,
  motivo_excepcion         VARCHAR(40) NULL,

  -- Compatibilidad futura (informativos; no equivalen a recepción confirmada por RH)
  generado_docx_en         TIMESTAMPTZ NULL,
  generaciones_docx_count  INTEGER NOT NULL DEFAULT 0,
  entrega_declarada_en     TIMESTAMPTZ NULL,
  entrega_declarada_por    UUID NULL REFERENCES public.app_users(id),

  -- Trazabilidad operativa básica (auditoría completa en public.app_audit_logs desde backend)
  creado_por               UUID NULL REFERENCES public.app_users(id),
  actualizado_por          UUID NULL REFERENCES public.app_users(id),
  creado_en                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT uq_rh_asis_entrega_persona_anio_mes
    UNIQUE (persona_id, anio, mes),

  CONSTRAINT chk_rh_asis_entrega_anio
    CHECK (anio BETWEEN 2020 AND 2100),

  CONSTRAINT chk_rh_asis_entrega_mes
    CHECK (mes BETWEEN 1 AND 12),

  CONSTRAINT chk_rh_asis_entrega_estado
    CHECK (estado IN (
      'PENDIENTE',
      'ENTREGADA_DECLARADA',
      'RECIBIDA',
      'OBSERVADA',
      'NO_APLICA'
    )),

  CONSTRAINT chk_rh_asis_entrega_motivo_excepcion
    CHECK (
      motivo_excepcion IS NULL
      OR motivo_excepcion IN (
        'INGRESO_POSTERIOR',
        'BAJA_PREVIA',
        'TRANSFERENCIA',
        'COMISION_EXTERNA',
        'LICENCIA_INCAPACIDAD',
        'EXENCION_ADMINISTRATIVA',
        'OTRO'
      )
    ),

  -- Solo el estado RECIBIDA tiene fecha_recepcion y recibido_por.
  -- Permite correcciones administrativas futuras limpiando ambos campos al cambiar de estado.
  CONSTRAINT chk_rh_asis_entrega_coherencia_recepcion
    CHECK (
      (estado = 'RECIBIDA' AND fecha_recepcion IS NOT NULL AND recibido_por IS NOT NULL)
      OR (estado <> 'RECIBIDA' AND fecha_recepcion IS NULL AND recibido_por IS NULL)
    ),

  -- Solo el estado NO_APLICA marca excepcion_administrativa = TRUE con motivo_excepcion.
  CONSTRAINT chk_rh_asis_entrega_coherencia_excepcion
    CHECK (
      (estado = 'NO_APLICA' AND excepcion_administrativa IS TRUE AND motivo_excepcion IS NOT NULL)
      OR (estado <> 'NO_APLICA' AND excepcion_administrativa IS FALSE AND motivo_excepcion IS NULL)
    ),

  -- Cuando el motivo de excepción es OTRO, se exige justificación en observaciones.
  CONSTRAINT chk_rh_asis_entrega_motivo_otro_obs
    CHECK (
      motivo_excepcion IS DISTINCT FROM 'OTRO'
      OR NULLIF(BTRIM(observaciones), '') IS NOT NULL
    ),

  -- Cuando el estado es OBSERVADA, se exige registrar el motivo/detalle en observaciones.
  CONSTRAINT chk_rh_asis_entrega_observada_obs
    CHECK (
      estado <> 'OBSERVADA'
      OR NULLIF(BTRIM(observaciones), '') IS NOT NULL
    ),

  CONSTRAINT chk_rh_asis_entrega_gen_count
    CHECK (generaciones_docx_count >= 0),

  CONSTRAINT chk_rh_asis_entrega_declaracion
    CHECK (
      (entrega_declarada_en IS NULL AND entrega_declarada_por IS NULL)
      OR (entrega_declarada_en IS NOT NULL AND entrega_declarada_por IS NOT NULL)
    )
);

COMMENT ON TABLE public.rh_asistencia_entrega_mensual IS
  'Control mensual de entrega y recepción de listas de asistencia por trabajador (persona_id, anio, mes). Separa generación DOCX, declaración de entrega, recepción confirmada por RH y excepciones administrativas. No almacena archivos ni firmas; sin borrado físico.';

COMMENT ON COLUMN public.rh_asistencia_entrega_mensual.unidad_medica_id IS
  'Unidad médica o administrativa de referencia del seguimiento en el periodo (opcional; permite seguimiento aun sin adscripción formal).';

COMMENT ON COLUMN public.rh_asistencia_entrega_mensual.adscripcion_laboral_id IS
  'Referencia opcional a public.rh_adscripcion_laboral; nullable para no bloquear casos sin adscripción formal registrada.';

COMMENT ON COLUMN public.rh_asistencia_entrega_mensual.estado IS
  'Estado oficial del control: PENDIENTE, ENTREGADA_DECLARADA, RECIBIDA, OBSERVADA o NO_APLICA. Solo RECIBIDA representa recepción conforme confirmada por RH.';

COMMENT ON COLUMN public.rh_asistencia_entrega_mensual.excepcion_administrativa IS
  'Indica que RH registró explícitamente que el trabajador no está obligado a entregar lista en ese periodo (estado = NO_APLICA).';

COMMENT ON COLUMN public.rh_asistencia_entrega_mensual.motivo_excepcion IS
  'Catálogo controlado del motivo de excepción administrativa: INGRESO_POSTERIOR, BAJA_PREVIA, TRANSFERENCIA, COMISION_EXTERNA, LICENCIA_INCAPACIDAD, EXENCION_ADMINISTRATIVA u OTRO.';

COMMENT ON COLUMN public.rh_asistencia_entrega_mensual.generado_docx_en IS
  'Marca informativa de última generación del documento DOCX en plataforma; NO equivale a entrega ni a recepción.';

COMMENT ON COLUMN public.rh_asistencia_entrega_mensual.entrega_declarada_en IS
  'Marca informativa de declaración de entrega por el trabajador; NO equivale a recepción confirmada por RH.';

-- Índices para consultas operativas y reportes por periodo, unidad, estado y persona
CREATE INDEX IF NOT EXISTS idx_rh_asis_entrega_periodo_estado
  ON public.rh_asistencia_entrega_mensual (anio, mes, estado);

CREATE INDEX IF NOT EXISTS idx_rh_asis_entrega_unidad_periodo
  ON public.rh_asistencia_entrega_mensual (unidad_medica_id, anio, mes);

CREATE INDEX IF NOT EXISTS idx_rh_asis_entrega_persona_periodo
  ON public.rh_asistencia_entrega_mensual (persona_id, anio DESC, mes DESC);

CREATE INDEX IF NOT EXISTS idx_rh_asis_entrega_excepcion
  ON public.rh_asistencia_entrega_mensual (anio, mes, motivo_excepcion)
  WHERE excepcion_administrativa IS TRUE;

COMMIT;

