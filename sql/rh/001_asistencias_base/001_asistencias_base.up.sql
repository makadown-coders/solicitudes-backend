-- =============================================================================
-- MICROINTERVENCIÓN RH-DB.1 — MIGRACIÓN UP
-- Archivo: sql/rh/001_asistencias_base/001_asistencias_base.up.sql
-- Objetivo:
--   Crear las estructuras mínimas iniciales para el módulo de Recursos Humanos
--   (Listas de Asistencia) sobre PostgreSQL 17.4, reutilizando public.persona,
--   public.unidad_medica y public.app_users sin modificar tablas existentes.
-- =============================================================================

BEGIN;

-- 1. Datos laborales complementarios y vigencias por persona/unidad
CREATE TABLE IF NOT EXISTS public.rh_adscripcion_laboral (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  persona_id        integer NOT NULL REFERENCES public.persona(id),
  unidad_medica_id  integer NOT NULL REFERENCES public.unidad_medica(id),
  matricula         varchar(64) NULL,
  puesto            varchar(160) NULL,
  turno             varchar(60) NULL,
  jornada           varchar(80) NULL,
  horario           varchar(120) NULL,
  vigente_desde     date NOT NULL,
  vigente_hasta     date NULL,
  activo            boolean NOT NULL DEFAULT true,
  observaciones     text NULL,
  creado_en         timestamptz NOT NULL DEFAULT now(),
  actualizado_en    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_rh_adscripcion_vigencia
    CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
  CONSTRAINT uq_rh_adscripcion_id_persona_unidad
    UNIQUE (id, persona_id, unidad_medica_id)
);

COMMENT ON TABLE public.rh_adscripcion_laboral IS
  'Datos laborales complementarios e historial de adscripciones de public.persona en public.unidad_medica.';

CREATE INDEX IF NOT EXISTS idx_rh_adscripcion_persona
  ON public.rh_adscripcion_laboral (persona_id, vigente_desde DESC);

CREATE INDEX IF NOT EXISTS idx_rh_adscripcion_unidad
  ON public.rh_adscripcion_laboral (unidad_medica_id, activo);

-- 2. Periodos mensuales de asistencia
CREATE TABLE IF NOT EXISTS public.rh_periodo_asistencia (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anio            smallint NOT NULL,
  mes             smallint NOT NULL,
  fecha_inicio    date NOT NULL,
  fecha_fin       date NOT NULL,
  estado          varchar(20) NOT NULL DEFAULT 'ABIERTO',
  creado_en       timestamptz NOT NULL DEFAULT now(),
  actualizado_en  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_rh_periodo_anio_mes UNIQUE (anio, mes),
  CONSTRAINT chk_rh_periodo_anio CHECK (anio BETWEEN 2000 AND 2100),
  CONSTRAINT chk_rh_periodo_mes CHECK (mes BETWEEN 1 AND 12),
  CONSTRAINT chk_rh_periodo_fechas CHECK (
    fecha_fin >= fecha_inicio
    AND fecha_inicio = make_date(anio::int, mes::int, 1)
    AND fecha_fin = (make_date(anio::int, mes::int, 1) + INTERVAL '1 month - 1 day')::date
  ),
  CONSTRAINT chk_rh_periodo_estado CHECK (estado IN ('ABIERTO', 'CERRADO'))
);

COMMENT ON TABLE public.rh_periodo_asistencia IS
  'Catálogo de periodos mensuales para listas de asistencia de Recursos Humanos.';

-- 3. Lista mensual de asistencia por trabajador, periodo y unidad
CREATE TABLE IF NOT EXISTS public.rh_lista_asistencia (
  id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo_id              integer NOT NULL REFERENCES public.rh_periodo_asistencia(id),
  persona_id              integer NOT NULL REFERENCES public.persona(id),
  unidad_medica_id        integer NOT NULL REFERENCES public.unidad_medica(id),
  adscripcion_laboral_id  integer NULL REFERENCES public.rh_adscripcion_laboral(id),
  matricula_snapshot      varchar(64) NULL,
  puesto_snapshot         varchar(160) NULL,
  turno_snapshot          varchar(60) NULL,
  jornada_snapshot        varchar(80) NULL,
  horario_snapshot        varchar(120) NULL,
  estado                  varchar(20) NOT NULL DEFAULT 'BORRADOR',
  documento_referencia    text NULL,
  observaciones           text NULL,
  creado_por              uuid NULL REFERENCES public.app_users(id),
  actualizado_por         uuid NULL REFERENCES public.app_users(id),
  creado_en               timestamptz NOT NULL DEFAULT now(),
  actualizado_en          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_rh_lista_periodo_persona_unidad
    UNIQUE (periodo_id, persona_id, unidad_medica_id),
  CONSTRAINT fk_rh_lista_adscripcion_coherente
    FOREIGN KEY (adscripcion_laboral_id, persona_id, unidad_medica_id)
    REFERENCES public.rh_adscripcion_laboral (id, persona_id, unidad_medica_id),
  CONSTRAINT chk_rh_lista_estado
    CHECK (estado IN ('BORRADOR', 'CAPTURADA', 'VALIDADA', 'CERRADA'))
);

COMMENT ON TABLE public.rh_lista_asistencia IS
  'Lista mensual de asistencia por trabajador, periodo y unidad médica. Incluye snapshot laboral histórico.';

CREATE INDEX IF NOT EXISTS idx_rh_lista_unidad_periodo
  ON public.rh_lista_asistencia (unidad_medica_id, periodo_id);

CREATE INDEX IF NOT EXISTS idx_rh_lista_persona_periodo
  ON public.rh_lista_asistencia (persona_id, periodo_id);

-- 4. Detalle diario de entradas y salidas por lista mensual
CREATE TABLE IF NOT EXISTS public.rh_asistencia_detalle (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lista_asistencia_id  integer NOT NULL REFERENCES public.rh_lista_asistencia(id) ON DELETE CASCADE,
  fecha                date NOT NULL,
  hora_entrada         time without time zone NULL,
  hora_salida          time without time zone NULL,
  observaciones        text NULL,
  creado_en            timestamptz NOT NULL DEFAULT now(),
  actualizado_en       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_rh_detalle_lista_fecha
    UNIQUE (lista_asistencia_id, fecha)
);

COMMENT ON TABLE public.rh_asistencia_detalle IS
  'Registro diario de hora de entrada y salida por lista mensual. Permite NULL y turnos nocturnos (entrada > salida).';

CREATE INDEX IF NOT EXISTS idx_rh_detalle_fecha
  ON public.rh_asistencia_detalle (fecha);

COMMIT;
