BEGIN;

CREATE TABLE IF NOT EXISTS public.solicitud_primer_nivel_contexto (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  solicitud_id uuid NOT NULL
    REFERENCES public.solicitud_bitacora(id) ON DELETE CASCADE,
  clave text NOT NULL,
  cantidad_capturada integer NOT NULL CHECK (cantidad_capturada > 0),
  origen_captura text NOT NULL
    CHECK (origen_captura IN ('APS', 'PROGRAMA_PREVENTIVO', 'CLAVE')),
  referencia_captura text NULL,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (origen_captura = 'CLAVE' AND referencia_captura IS NULL)
    OR
    (origen_captura <> 'CLAVE' AND referencia_captura IS NOT NULL AND btrim(referencia_captura) <> '')
  )
);

CREATE INDEX IF NOT EXISTS ix_solicitud_primer_nivel_contexto_solicitud
  ON public.solicitud_primer_nivel_contexto (solicitud_id);

CREATE INDEX IF NOT EXISTS ix_solicitud_primer_nivel_contexto_clave
  ON public.solicitud_primer_nivel_contexto (clave);

CREATE INDEX IF NOT EXISTS ix_solicitud_primer_nivel_contexto_origen_referencia
  ON public.solicitud_primer_nivel_contexto (origen_captura, referencia_captura);

COMMIT;
